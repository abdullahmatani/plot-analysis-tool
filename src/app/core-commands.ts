import {
  FilePlus2,
  FolderOpen,
  Save,
  SaveAll,
  Download,
  X,
  Undo2,
  Redo2,
  History,
  Bookmark,
  Sun,
  Moon,
  Monitor,
  PanelRight,
  PanelLeft,
  Command as CommandIcon,
  Keyboard,
  Info,
  Settings,
  HardDrive,
  LifeBuoy,
} from 'lucide-react';
import { toast } from 'sonner';

import { useProjectStore } from '@/store/project';
import { useUiStore } from '@/store/ui';

import { registerCommands } from './commands';
import { closeProject, downloadBackup, openProjectFile, saveProject, saveProjectAs } from './file-ops';
import { promptText } from './prompt';
import { currentSession } from './session';

const hasProject = () => !!useProjectStore.getState().history;
const canEdit = () => hasProject() && !useProjectStore.getState().readOnly;

export function registerCoreCommands() {
  return registerCommands([
    {
      id: 'file.new',
      title: 'New project',
      menu: 'File',
      section: 'project',
      shortcut: 'Alt+N',
      icon: FilePlus2,
      run: () => useUiStore.getState().openDialog('new-project'),
    },
    {
      id: 'file.open',
      title: 'Open project file…',
      menu: 'File',
      section: 'project',
      shortcut: 'Mod+O',
      icon: FolderOpen,
      run: () => openProjectFile(),
    },
    {
      id: 'file.save',
      title: 'Save to file',
      menu: 'File',
      section: 'save',
      shortcut: 'Mod+S',
      icon: Save,
      needsProject: true,
      enabled: hasProject,
      run: () => void saveProject(),
    },
    {
      id: 'file.saveAs',
      title: 'Save as…',
      menu: 'File',
      section: 'save',
      shortcut: 'Mod+Alt+S',
      icon: SaveAll,
      needsProject: true,
      enabled: hasProject,
      run: () => void saveProjectAs(),
    },
    {
      id: 'file.backup',
      title: 'Download backup copy',
      menu: 'File',
      section: 'save',
      icon: Download,
      needsProject: true,
      enabled: hasProject,
      run: () => downloadBackup(),
    },
    {
      id: 'file.close',
      title: 'Close project',
      menu: 'File',
      section: 'close',
      icon: X,
      needsProject: true,
      enabled: hasProject,
      run: () => closeProject(),
    },
    {
      id: 'file.history',
      title: 'Restore points…',
      menu: 'File',
      section: 'history',
      shortcut: 'Mod+Alt+H',
      icon: History,
      needsProject: true,
      enabled: hasProject,
      run: () => useUiStore.getState().openDialog('history'),
    },
    {
      id: 'file.restorePoint',
      title: 'Create named restore point',
      menu: 'File',
      section: 'history',
      shortcut: 'Mod+Shift+S',
      icon: Bookmark,
      needsProject: true,
      enabled: canEdit,
      run: async () => {
        const label = await promptText({
          title: 'Create restore point',
          label: 'Name',
          defaultValue: `Checkpoint ${new Date().toLocaleString()}`,
        });
        if (!label) return;
        const rec = await currentSession()?.createNamedRestorePoint(label);
        if (rec) toast.success(`Restore point "${label}" created`);
      },
    },
    {
      id: 'edit.undo',
      title: 'Undo',
      menu: 'Edit',
      section: 'history',
      shortcut: 'Mod+Z',
      icon: Undo2,
      needsProject: true,
      enabled: () => canEdit() && (useProjectStore.getState().history?.undo.length ?? 0) > 0,
      run: () => void useProjectStore.getState().undo(),
    },
    {
      id: 'edit.redo',
      title: 'Redo',
      menu: 'Edit',
      section: 'history',
      shortcut: 'Mod+Shift+Z',
      icon: Redo2,
      needsProject: true,
      enabled: () => canEdit() && (useProjectStore.getState().history?.redo.length ?? 0) > 0,
      run: () => void useProjectStore.getState().redo(),
    },
    {
      id: 'edit.redoAlt',
      title: 'Redo (alternative)',
      menu: 'Edit',
      hidden: true,
      shortcut: 'Mod+Y',
      needsProject: true,
      enabled: () => canEdit(),
      run: () => void useProjectStore.getState().redo(),
    },
    {
      id: 'view.themeLight',
      title: 'Light theme',
      menu: 'View',
      section: 'theme',
      icon: Sun,
      checked: () => useUiStore.getState().theme === 'light',
      run: () => useUiStore.getState().setTheme('light'),
    },
    {
      id: 'view.themeDark',
      title: 'Dark theme',
      menu: 'View',
      section: 'theme',
      icon: Moon,
      checked: () => useUiStore.getState().theme === 'dark',
      run: () => useUiStore.getState().setTheme('dark'),
    },
    {
      id: 'view.themeSystem',
      title: 'System theme',
      menu: 'View',
      section: 'theme',
      icon: Monitor,
      checked: () => useUiStore.getState().theme === 'system',
      run: () => useUiStore.getState().setTheme('system'),
    },
    {
      id: 'view.canvasDark',
      title: 'Dark canvas background',
      menu: 'View',
      section: 'canvas',
      checked: () => useUiStore.getState().canvasBg === 'dark',
      run: () => useUiStore.getState().setCanvasBg('dark'),
    },
    {
      id: 'view.canvasLight',
      title: 'Light canvas background',
      menu: 'View',
      section: 'canvas',
      checked: () => useUiStore.getState().canvasBg === 'light',
      run: () => useUiStore.getState().setCanvasBg('light'),
    },
    {
      id: 'view.toggleInspector',
      title: 'Toggle inspector panel',
      menu: 'View',
      section: 'panels',
      shortcut: 'Mod+Alt+I',
      icon: PanelRight,
      checked: () => useUiStore.getState().inspectorOpen,
      run: () => useUiStore.getState().toggleInspector(),
    },
    {
      id: 'view.toggleToolRail',
      title: 'Toggle tool rail',
      menu: 'View',
      section: 'panels',
      shortcut: 'Mod+Alt+T',
      icon: PanelLeft,
      checked: () => useUiStore.getState().toolRailOpen,
      run: () => useUiStore.getState().toggleToolRail(),
    },
    {
      id: 'help.palette',
      title: 'Command palette',
      menu: 'Help',
      section: 'cmd',
      shortcut: 'Mod+K',
      icon: CommandIcon,
      run: () => useUiStore.getState().setPaletteOpen(true),
    },
    {
      id: 'help.shortcuts',
      title: 'Keyboard shortcuts',
      menu: 'Help',
      section: 'cmd',
      shortcut: 'Shift+?',
      icon: Keyboard,
      run: () => useUiStore.getState().openDialog('shortcuts'),
    },
    {
      id: 'help.guide',
      title: 'Help and workflow guides',
      menu: 'Help',
      section: 'help',
      shortcut: 'F1',
      icon: LifeBuoy,
      run: () => useUiStore.getState().openDialog('help'),
    },
    {
      id: 'help.settings',
      title: 'Settings…',
      menu: 'Help',
      section: 'settings',
      shortcut: 'Mod+,',
      icon: Settings,
      run: () => useUiStore.getState().openDialog('settings'),
    },
    {
      id: 'help.storage',
      title: 'Storage and local data…',
      menu: 'Help',
      section: 'settings',
      icon: HardDrive,
      run: () => useUiStore.getState().openDialog('storage'),
    },
    {
      id: 'help.about',
      title: 'About, privacy and licences',
      menu: 'Help',
      section: 'about',
      icon: Info,
      run: () => useUiStore.getState().openDialog('about'),
    },
  ]);
}
