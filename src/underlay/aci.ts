/** ACI index of the background-adaptive white/black colour. */
export const ACI_WHITE = 7;

/** RGB (0xRRGGBB) for an ACI index; out-of-range or logical indices (0, 256, 257) map to white. */
export function aciToRgb(i: number): number {
  const k = Math.abs(Math.trunc(i));
  return k >= 1 && k <= 255 ? ACI_RGB[k] : 0xffffff;
}
